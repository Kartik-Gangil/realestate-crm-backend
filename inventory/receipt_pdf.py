from decimal import Decimal, InvalidOperation
from io import BytesIO
import re

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas


def _pdf_text(value):
    """Keep the receipt compatible with the built-in Helvetica font."""
    return str(value or "-").encode("ascii", "replace").decode("ascii")


def _money(value):
    try:
        amount = Decimal(str(value or "0"))
    except (InvalidOperation, TypeError, ValueError):
        amount = Decimal("0")
    return f"INR {amount:,.2f}"


def _safe_filename(value):
    return re.sub(r"[^A-Za-z0-9._-]+", "_", _pdf_text(value)) or "receipt"


def payment_receipt_pdf(payment, receipt):
    """Render a printable payment receipt as valid PDF bytes."""
    output = BytesIO()
    # Keep the single-page receipt easy for PDF viewers and support tools to
    # inspect; the document is small enough that compression is unnecessary.
    document = canvas.Canvas(output, pagesize=A4, pageCompression=0)
    width, height = A4
    document.setTitle(f"Payment Receipt {receipt.receipt_number}")

    booking = payment.booking
    if booking is None:
        allocation = payment.payment_allocations.select_related(
            "booking__lead", "booking__plot"
        ).first()
        booking = allocation.booking if allocation else None

    customer = booking.customer if booking else None
    plot = booking.plot if booking else None

    left = 22 * mm
    right = width - 22 * mm
    y = height - 24 * mm

    document.setFillColor(colors.HexColor("#0B2A4A"))
    document.rect(0, height - 42 * mm, width, 42 * mm, fill=1, stroke=0)
    document.setFillColor(colors.white)
    document.setFont("Helvetica-Bold", 20)
    document.drawString(left, height - 20 * mm, "PAYMENT RECEIPT")
    document.setFont("Helvetica", 9)
    document.drawRightString(right, height - 19 * mm, _pdf_text(receipt.receipt_number))
    document.drawRightString(right, height - 25 * mm, "Shriji CRM")

    y = height - 58 * mm
    document.setFillColor(colors.HexColor("#0B2A4A"))
    document.setFont("Helvetica-Bold", 11)
    document.drawString(left, y, "Receipt details")
    y -= 8 * mm

    details = [
        ("Receipt number", receipt.receipt_number),
        ("Payment reference", payment.payment_id),
        ("Payment date", payment.payment_date.isoformat()),
        ("Payment mode", str(payment.payment_method).replace("_", " ").title()),
        ("Transaction reference", payment.transaction_reference),
        ("Status", str(payment.status).title()),
    ]
    document.setFont("Helvetica", 10)
    for label, value in details:
        document.setFillColor(colors.HexColor("#667085"))
        document.drawString(left, y, _pdf_text(label))
        document.setFillColor(colors.HexColor("#101828"))
        document.drawString(left + 47 * mm, y, _pdf_text(value))
        y -= 7 * mm

    y -= 4 * mm
    document.setStrokeColor(colors.HexColor("#D0D5DD"))
    document.line(left, y, right, y)
    y -= 10 * mm
    document.setFillColor(colors.HexColor("#0B2A4A"))
    document.setFont("Helvetica-Bold", 11)
    document.drawString(left, y, "Customer and booking")
    y -= 8 * mm

    customer_name = customer.full_name if customer else "-"
    booking_number = f"Booking #{booking.id}" if booking else "-"
    plot_number = plot.plot_number if plot else "-"
    booking_details = [
        ("Customer", customer_name),
        ("Booking", booking_number),
        ("Plot", plot_number),
    ]
    document.setFont("Helvetica", 10)
    for label, value in booking_details:
        document.setFillColor(colors.HexColor("#667085"))
        document.drawString(left, y, _pdf_text(label))
        document.setFillColor(colors.HexColor("#101828"))
        document.drawString(left + 47 * mm, y, _pdf_text(value))
        y -= 7 * mm

    y -= 5 * mm
    document.setFillColor(colors.HexColor("#EAF2FA"))
    document.roundRect(left, y - 18 * mm, right - left, 18 * mm, 3 * mm, fill=1, stroke=0)
    document.setFillColor(colors.HexColor("#0B2A4A"))
    document.setFont("Helvetica-Bold", 11)
    document.drawString(left + 6 * mm, y - 7 * mm, "Amount received")
    document.setFont("Helvetica-Bold", 16)
    document.drawRightString(right - 6 * mm, y - 8 * mm, _money(payment.amount))

    document.setFillColor(colors.HexColor("#667085"))
    document.setFont("Helvetica", 8)
    document.drawString(left, 20 * mm, "This is a system-generated receipt for a manually recorded payment.")
    document.drawRightString(right, 20 * mm, "Generated by Shriji CRM")

    document.showPage()
    document.save()
    return output.getvalue()


def payment_receipt_filename(receipt):
    return f"Receipt_{_safe_filename(receipt.receipt_number)}.pdf"


def booking_receipt_pdf(booking):
    """Render the Phase 9 booking summary receipt."""
    output = BytesIO()
    document = canvas.Canvas(output, pagesize=A4, pageCompression=0)
    width, height = A4
    receipt_number = booking.booking_receipt_number or booking.booking_code or f"BKG-{booking.pk}"
    document.setTitle(f"Booking Receipt {receipt_number}")
    left, right = 22 * mm, width - 22 * mm
    document.setFillColor(colors.HexColor("#0B2A4A"))
    document.rect(0, height - 42 * mm, width, 42 * mm, fill=1, stroke=0)
    document.setFillColor(colors.white)
    document.setFont("Helvetica-Bold", 20)
    document.drawString(left, height - 20 * mm, "BOOKING RECEIPT")
    document.setFont("Helvetica", 9)
    document.drawRightString(right, height - 19 * mm, _pdf_text(receipt_number))
    y = height - 58 * mm
    document.setFillColor(colors.HexColor("#101828"))
    document.setFont("Helvetica", 10)
    rows = [
        ("Booking code", booking.booking_code or f"BKG-{booking.pk}"),
        ("Customer", booking.customer.full_name if booking.customer_id else booking.lead.full_name),
        ("Plot", booking.plot.plot_number),
        ("Status", booking.status),
        ("Net amount", _money(booking.net_amount or booking.final_price)),
    ]
    for label, value in rows:
        document.setFillColor(colors.HexColor("#667085"))
        document.drawString(left, y, _pdf_text(label))
        document.setFillColor(colors.HexColor("#101828"))
        document.drawString(left + 47 * mm, y, _pdf_text(value))
        y -= 8 * mm
    document.setFillColor(colors.HexColor("#667085"))
    document.setFont("Helvetica", 8)
    document.drawString(left, 20 * mm, "This is a system-generated booking receipt.")
    document.showPage()
    document.save()
    return output.getvalue()
